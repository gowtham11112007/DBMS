-- Ex 2: DDL commands with constraints (PRIMARY, FOREIGN KEY, UNIQUE, CHECK)
DROP DATABASE IF EXISTS dbms_lab;
CREATE DATABASE dbms_lab;
USE dbms_lab;

-- tables from Ex 1
CREATE TABLE STUDENT (RegNo INT, Name VARCHAR(15), Gender CHAR(1), DOB DATE, MobileNo BIGINT, City VARCHAR(15));
CREATE TABLE FACULTY (FacNo VARCHAR(4), FacName VARCHAR(15), Gender CHAR(1), DOB DATE, DOJ DATE, MobileNo BIGINT);
CREATE TABLE DEPARTMENT (DeptNo VARCHAR(4), DeptName VARCHAR(15), DeptHead VARCHAR(4));
CREATE TABLE COURSE (CourseNo VARCHAR(3), CourseDesc VARCHAR(14), CourseType CHAR(1), SemNo CHAR(1), HallNo VARCHAR(4), FacNo VARCHAR(4));
CREATE TABLE STUDENT2 (RegNo INT, S1Name VARCHAR(15), City VARCHAR(15));
CREATE TABLE STUDENT3 (RegNo INT, Mark INT);

-- 1) STUDENT2: RegNo primary key
ALTER TABLE STUDENT2 ADD PRIMARY KEY (RegNo);
DESC STUDENT2;

-- 2) FACULTY: FacNo primary key, Gender check 'M' or 'F'
ALTER TABLE FACULTY ADD PRIMARY KEY (FacNo);
ALTER TABLE FACULTY ADD CONSTRAINT chk_fac_gender CHECK (Gender IN ('M','F'));
SHOW CREATE TABLE FACULTY;

-- 3) DEPARTMENT: DeptNo primary key
ALTER TABLE DEPARTMENT ADD PRIMARY KEY (DeptNo);
DESC DEPARTMENT;

-- 4) COURSE: CourseNo primary key, SemNo 1 to 6
ALTER TABLE COURSE ADD PRIMARY KEY (CourseNo);
ALTER TABLE COURSE ADD CONSTRAINT chk_sem CHECK (SemNo BETWEEN '1' AND '6');
SHOW CREATE TABLE COURSE;

-- 5) STUDENT2: S1Name unique
ALTER TABLE STUDENT2 ADD CONSTRAINT uq_s1name UNIQUE (S1Name);
SHOW CREATE TABLE STUDENT2;

-- 6) STUDENT3: foreign key RegNo -> STUDENT2(RegNo)
ALTER TABLE STUDENT3 ADD CONSTRAINT fk_student3_reg FOREIGN KEY (RegNo) REFERENCES STUDENT2(RegNo) ON DELETE CASCADE ON UPDATE CASCADE;
SHOW CREATE TABLE STUDENT3;
